import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import cookieParser from 'cookie-parser';
import { randomUUID } from 'node:crypto';
import api from './routes/api.js';
const app=express();
const allowedOrigins=new Set((process.env.CLIENT_ORIGIN||'http://localhost:5173').split(',').map(origin=>origin.trim().replace(/\/$/, '')).filter(Boolean));
const proxyHops=Number.parseInt(process.env.TRUST_PROXY_HOPS||'0',10);
if(Number.isInteger(proxyHops)&&proxyHops>0)app.set('trust proxy',proxyHops);
app.use(helmet());
app.use(cors({origin(origin,callback){callback(null,!origin||allowedOrigins.has(origin));},credentials:true}));
app.use(express.json({limit:'32kb'}));app.use(cookieParser());
const sameSite=(process.env.COOKIE_SAME_SITE||'lax').toLowerCase();
if(!['lax','strict','none'].includes(sameSite))throw new Error('COOKIE_SAME_SITE must be lax, strict, or none.');
app.use((req,res,next)=>{req.guestId=req.cookies?.guest_id||randomUUID();if(!req.cookies?.guest_id)res.cookie('guest_id',req.guestId,{httpOnly:true,sameSite,secure:process.env.NODE_ENV==='production'||sameSite==='none',maxAge:31536000000});next();});
app.use('/api/v1',api);
app.use('/api/v1',(req,res)=>res.status(404).json({error:{code:'ROUTE_NOT_FOUND',message:'That API route was not found.'}}));
app.use((err,_req,res,_next)=>{if(err.type==='entity.parse.failed')return res.status(400).json({error:{code:'INVALID_JSON',message:'Request body must be valid JSON.'}});if(err.type==='entity.too.large')return res.status(413).json({error:{code:'REQUEST_TOO_LARGE',message:'Request body is too large.'}});console.error(err);res.status(500).json({error:{code:'INTERNAL_ERROR',message:'Something went wrong. Please try again.'}});});
export default app;
